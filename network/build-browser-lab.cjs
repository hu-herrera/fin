'use strict';
const fs=require('node:fs');
const path=require('node:path');
const model=fs.readFileSync(path.join(__dirname,'redundant-model.cjs'),'utf8');
const configs=fs.readFileSync(path.join(__dirname,'redundant-configs.cjs'),'utf8');
function exportsOf(s){
 const m=s.match(/module\.exports\s*=\s*(\{[^;]+\});\s*$/);
 if(!m)throw Error('module.exports no encontrado');
 return m[1];
}
const modelBody=model.replace(/module\.exports\s*=\s*(\{[^;]+\});\s*$/,'');
const configBody=configs.replace(/^const \{PORTS,VLAN,candidateAddressing,checkSiteNum\}=require\('\.\/redundant-model\.cjs'\);\s*$/m,
 'const {PORTS,VLAN,candidateAddressing,checkSiteNum}=MODEL;')
 .replace(/module\.exports\s*=\s*(\{[^;]+\});\s*$/,'');
const browser=[
 '/* Generated by network/build-browser-lab.cjs. Node source files are authoritative. */',
 '(function(root){',
 "'use strict';",
 modelBody,
 'const MODEL='+exportsOf(model)+';',
 'const CONFIGS=(function(){',
 configBody,
 'return '+exportsOf(configs)+';',
 '})();',
 'root.RedundantLab=Object.freeze({...MODEL,...CONFIGS});',
 '})(window);',
 ''].join('\n');
new Function(browser);
const target=path.join(__dirname,'redundant-browser.js');
if(process.argv.includes('--check')){
 if(fs.readFileSync(target,'utf8')!==browser)throw Error('Browser lab desactualizado: ejecutar node network/build-browser-lab.cjs');
 console.log('OK: motor Node y navegador sincronizados');
}else{fs.writeFileSync(target,browser); console.log('Generado '+target)}
